
import os
import json
import uuid
import logging
import pandas as pd

from connect import get_connection


# --------------------------------------------------
# CONFIGURATION
# --------------------------------------------------

CSV_FILE = "../csv_files/property_details.csv"

# Create the log folder if it does not exist.
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOG_DIR = os.path.join(BASE_DIR, "scraper_logs")
os.makedirs(LOG_DIR, exist_ok=True)

# Store insertion errors in a log file.
logging.basicConfig(
    filename=os.path.join(LOG_DIR, "TU360insert.log"),
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s",
    encoding="utf-8"
)

logger = logging.getLogger(__name__)


# --------------------------------------------------
# HELPER FUNCTIONS
# --------------------------------------------------

def clean_value(value):
    """
    Convert pandas NaN values and empty strings to None.
    MySQL Connector inserts None as SQL NULL.
    """

    if value is None:
        return None

    # Check for missing pandas values.
    try:
        if pd.isna(value):
            return None
    except (TypeError, ValueError):
        pass

    # Remove unnecessary spaces from strings.
    if isinstance(value, str):
        value = value.strip()

        if value == "":
            return None

    return value


def generate_uuid(row):
    """
    Generate a stable UUID using the property link.
    If the link is missing, use web_id instead.
    """

    link = clean_value(row.get("link"))
    web_id = clean_value(row.get("web_id"))

    identifier = link or web_id

    if not identifier:
        raise ValueError("Both link and web_id are missing.")

    return str(
        uuid.uuid5(uuid.NAMESPACE_URL, str(identifier))
    )


def serialize_json(value):
    """
    Handle fields that may contain JSON data.

    Lists and dictionaries are converted into JSON strings.
    Existing JSON strings are validated and preserved.
    Ordinary text is preserved as text.
    Missing values become None.
    """

    value = clean_value(value)

    if value is None:
        return None

    # Convert Python lists or dictionaries into JSON strings.
    if isinstance(value, (list, dict)):
        return json.dumps(value, ensure_ascii=False)

    # CSV fields usually contain JSON as strings.
    if isinstance(value, str):
        try:
            json.loads(value)

            # The string already contains valid JSON.
            return value

        except json.JSONDecodeError:
            # Keep ordinary text unchanged.
            return value

    return json.dumps(value, ensure_ascii=False)


def to_integer(value):
    """
    Convert numeric values into integers for MySQL columns.
    Return None if the value is missing or invalid.
    """

    value = clean_value(value)

    if value is None:
        return None

    try:
        return int(round(float(value)))
    except (ValueError, TypeError, OverflowError):
        return None


# --------------------------------------------------
# DATABASE INSERT
# --------------------------------------------------

def insert_properties():

    # Read the CSV generated by details.py.
    df = pd.read_csv(
        CSV_FILE,
        encoding="utf-8-sig"
    )

    print(f"Found {len(df)} properties in CSV.")

    if df.empty:
        print("CSV is empty. Nothing to insert.")
        return

    # Check that the CSV contains the required columns.
    required_columns = {"link", "web_id"}

    missing_columns = required_columns - set(df.columns)

    if missing_columns:
        raise ValueError(
            f"CSV is missing required columns: {missing_columns}"
        )

    connection = None
    cursor = None

    inserted_count = 0
    skipped_count = 0
    failed_count = 0

    try:
        # Connect to the MySQL database.
        connection = get_connection()
        cursor = connection.cursor()

        # Insert the CSV data into the hgchristie table.
        # Duplicate UUID or mls_id records are ignored.
        query = """
            INSERT IGNORE INTO hgchristie (
                uuid,
                title,
                link,
                location,
                country,
                lat,
                lng,
                latLng_status,
                type,
                phone,
                price,
                price_unit,
                details,
                img_src,
                about,
                exterior_acres,
                web_id,
                mls_id,
                bedrooms,
                full_baths,
                property_type,
                interior_sq_ft,
                amneties,
                features,
                partial_baths,
                change_price,
                sold_date,
                deleted_at,
                created_at,
                updated_at,
                city,
                new_features,
                property_details,
                exterior_details,
                interior_details,
                city_checked,
                province,
                property_status,
                neighbourhood,
                commercial_units,
                source_hash,
                first_seen_at,
                last_seen_at,
                missing_count,
                admin_price
            )
            VALUES (
                %s, %s, %s, %s, %s, %s, %s, %s, %s, %s,
                %s, %s, %s, %s, %s, %s, %s, %s, %s, %s,
                %s, %s, %s, %s, %s, %s, %s, %s, %s, %s,
                %s, %s, %s, %s, %s, %s, %s, %s, %s, %s,
                %s, NOW(), NOW(), 0, %s
            )
        """

        # Process each property separately.
        for index, row in df.iterrows():

            try:
                # Generate the property's stable UUID.
                property_uuid = generate_uuid(row)

                # Convert the pandas row into a dictionary.
                record = row.to_dict()

                # Handle fields that may contain JSON data.
                img_src = serialize_json(
                    record.get("img_src")
                )

                amneties = serialize_json(
                    record.get("amneties")
                )

                property_details = serialize_json(
                    record.get("property_details")
                )

                exterior_details = serialize_json(
                    record.get("exterior_details")
                )

                interior_details = serialize_json(
                    record.get("interior_details")
                )

                # Prepare values in the same order as the SQL columns.
                values = (
                    property_uuid,
                    clean_value(record.get("title")),
                    clean_value(record.get("link")),
                    clean_value(record.get("location")),
                    clean_value(record.get("country")),
                    clean_value(record.get("lat")),
                    clean_value(record.get("lng")),
                    to_integer(record.get("latLng_status")) or 0,
                    clean_value(record.get("type")),
                    clean_value(record.get("phone")),
                    to_integer(record.get("price")) or 0,
                    clean_value(record.get("price_unit")),
                    clean_value(record.get("details")),
                    img_src,
                    clean_value(record.get("about")),
                    clean_value(record.get("exterior_acres")),
                    clean_value(record.get("web_id")),
                    clean_value(record.get("mls_id")),
                    clean_value(record.get("bedrooms")),
                    clean_value(record.get("full_baths")),
                    clean_value(record.get("property_type")),
                    clean_value(record.get("interior_sq_ft")),
                    amneties,
                    clean_value(record.get("features")),
                    clean_value(record.get("partial_baths")),
                    clean_value(record.get("change_price")),
                    clean_value(record.get("sold_date")),
                    clean_value(record.get("deleted_at")),
                    clean_value(record.get("created_at")),
                    clean_value(record.get("updated_at")),
                    clean_value(record.get("city")),
                    clean_value(record.get("new_features")),
                    property_details,
                    exterior_details,
                    interior_details,
                    to_integer(record.get("city_checked")) or 0,
                    clean_value(record.get("province")),
                    clean_value(record.get("property_status")),
                    clean_value(record.get("neighbourhood")),
                    clean_value(record.get("commercial_units")),

                    # No SHA-256 hashing; leave source_hash as NULL.
                    None,

                    # first_seen_at, last_seen_at and missing_count
                    # are set directly in the SQL query.
                    to_integer(record.get("admin_price"))
                )

                # Replace missing values with None for MySQL.
                values = tuple(
                    clean_value(value)
                    for value in values
                )

                # Insert this property into the database.
                cursor.execute(query, values)

                # INSERT IGNORE returns rowcount 0 when a row is ignored.
                if cursor.rowcount == 1:
                    inserted_count += 1

                    print(
                        f"Inserted: {record.get('web_id')} | "
                        f"{record.get('title')}"
                    )

                else:
                    skipped_count += 1

                    print(
                        f"Skipped existing property: "
                        f"{record.get('web_id')}"
                    )

            except Exception as error:
                # Log the error for this row and continue with the next.
                failed_count += 1

                logger.exception(
                    "Failed to insert CSV row %s, web_id=%s",
                    index,
                    row.get("web_id")
                )

                print(
                    f"Failed row {index}: "
                    f"{row.get('web_id')} - {error}"
                )

        # Save all successful inserts.
        connection.commit()

        # Display the final insertion summary.
        print("\n----------- INSERT SUMMARY -----------")
        print(f"CSV properties: {len(df)}")
        print(f"Inserted:       {inserted_count}")
        print(f"Skipped:        {skipped_count}")
        print(f"Failed:         {failed_count}")
        print("--------------------------------------")

        logger.info(
            "Insertion completed. Total=%s, inserted=%s, "
            "skipped=%s, failed=%s",
            len(df),
            inserted_count,
            skipped_count,
            failed_count
        )

    except Exception:
        # Roll back if the overall database process fails.
        if connection:
            connection.rollback()

        logger.exception("Database insertion process failed")
        raise

    finally:
        # Always close database resources.
        if cursor:
            cursor.close()

        if connection:
            connection.close()


# --------------------------------------------------
# MAIN
# --------------------------------------------------

if __name__ == "__main__":
    insert_properties()
